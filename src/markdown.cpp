// ---- character helpers ----

bool is_digit(int c) { return c >= '0' && c <= '9'; }
bool is_alpha(int c) { return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z'); }
bool is_alnum(int c) { return is_digit(c) || is_alpha(c); }
bool is_xdigit(int c) { return is_digit(c) || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F'); }
bool is_sp_tab(int c) { return c == ' ' || c == '\t'; }
bool is_ws(int c) { return c == ' ' || c == '\t' || c == '\n' || c == '\r' || c == '\f' || c == '\v'; }
char lower(char c) { return c >= 'A' && c <= 'Z' ? static_cast<char>(c - 'A' + 'a') : c; }
char upper(char c) { return c >= 'a' && c <= 'z' ? static_cast<char>(c - 'a' + 'A') : c; }

bool is_ascii_punct(int c) {
  return (c >= 33 && c <= 47) || (c >= 58 && c <= 64) || (c >= 91 && c <= 96) ||
         (c >= 123 && c <= 126);
}

std::string to_lower(std::string_view s) {
  std::string out(s);
  for (auto& c : out) c = lower(c);
  return out;
}

bool iequals(std::string_view a, std::string_view b) {
  if (a.size() != b.size()) return false;
  for (size_t i = 0; i < a.size(); ++i) {
    if (lower(a[i]) != lower(b[i])) return false;
  }
  return true;
}

bool istarts(std::string_view s, std::string_view p) {
  return s.size() >= p.size() && iequals(s.substr(0, p.size()), p);
}

size_t ifind(std::string_view s, std::string_view needle) {
  if (needle.size() > s.size()) return npos;
  for (size_t i = 0; i + needle.size() <= s.size(); ++i) {
    if (iequals(s.substr(i, needle.size()), needle)) return i;
  }
  return npos;
}

bool is_blank(std::string_view s) {
  for (char c : s) {
    if (!is_ws(c)) return false;
  }
  return true;
}

std::string_view trim_ws(std::string_view s) {
  size_t b = 0, e = s.size();
  while (b < e && is_ws(s[b])) ++b;
  while (e > b && is_ws(s[e - 1])) --e;
  return s.substr(b, e - b);
}

std::string_view rtrim_sp(std::string_view s) {
  while (!s.empty() && is_sp_tab(s.back())) s.remove_suffix(1);
  return s;
}

// Decodes the code point at s[i] and advances i; malformed bytes decode as U+FFFD, one byte each.
uint32_t decode_utf8(std::string_view s, size_t& i) {
  const auto c = static_cast<unsigned char>(s[i]);
  if (c < 0x80) {
    ++i;
    return c;
  }
  int n = 0;
  uint32_t cp = 0;
  if (c >= 0xC2 && c <= 0xDF) {
    n = 1;
    cp = c & 0x1F;
  } else if (c >= 0xE0 && c <= 0xEF) {
    n = 2;
    cp = c & 0x0F;
  } else if (c >= 0xF0 && c <= 0xF4) {
    n = 3;
    cp = c & 0x07;
  } else {
    ++i;
    return 0xFFFD;
  }
  if (i + n >= s.size()) {
    ++i;
    return 0xFFFD;
  }
  for (int k = 1; k <= n; ++k) {
    const auto b = static_cast<unsigned char>(s[i + k]);
    if ((b & 0xC0) != 0x80) {
      ++i;
      return 0xFFFD;
    }
    cp = (cp << 6) | (b & 0x3F);
  }
  i += n + 1;
  return cp;
}

// Code point ending right before s[i] (i > 0).
uint32_t decode_utf8_before(std::string_view s, size_t i) {
  size_t j = i;
  for (int k = 0; k < 4 && j > 0; ++k) {
    --j;
    if ((static_cast<unsigned char>(s[j]) & 0xC0) != 0x80) break;
  }
  size_t p = j;
  const uint32_t cp = decode_utf8(s, p);
  return p == i ? cp : 0xFFFD;
}

void append_utf8(std::string& out, uint32_t cp) {
  if (cp < 0x80) {
    out += static_cast<char>(cp);
  } else if (cp < 0x800) {
    out += static_cast<char>(0xC0 | (cp >> 6));
    out += static_cast<char>(0x80 | (cp & 0x3F));
  } else if (cp < 0x10000) {
    out += static_cast<char>(0xE0 | (cp >> 12));
    out += static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
    out += static_cast<char>(0x80 | (cp & 0x3F));
  } else {
    out += static_cast<char>(0xF0 | (cp >> 18));
    out += static_cast<char>(0x80 | ((cp >> 12) & 0x3F));
    out += static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
    out += static_cast<char>(0x80 | (cp & 0x3F));
  }
}

// East Asian Wide / Fullwidth (two terminal columns).
bool is_wide(uint32_t cp) {
  static const uint32_t ranges[][2] = {
      {0x1100, 0x115F},  {0x2E80, 0x303E},  {0x3041, 0x33FF},   {0x3400, 0x4DBF},   {0x4E00, 0x9FFF},
      {0xA000, 0xA4CF},  {0xA960, 0xA97F},  {0xAC00, 0xD7A3},   {0xF900, 0xFAFF},   {0xFE10, 0xFE19},
      {0xFE30, 0xFE6F},  {0xFF00, 0xFF60},  {0xFFE0, 0xFFE6},   {0x1F300, 0x1F64F}, {0x1F900, 0x1F9FF},
      {0x20000, 0x3FFFD}};
  if (cp < 0x1100) return false;
  for (const auto& r : ranges) {
    if (cp >= r[0] && cp <= r[1]) return true;
  }
  return false;
}

// Display columns: 0 for combining marks and zero-width characters, 2 for wide ones.
int cp_cols(uint32_t cp) {
  if ((cp >= 0x300 && cp <= 0x36F) || (cp >= 0x200B && cp <= 0x200F) || cp == 0xFE0F) return 0;
  return is_wide(cp) ? 2 : 1;
}

int cp_width(std::string_view s) {
  int n = 0;
  for (size_t i = 0; i < s.size();) {
    if (static_cast<unsigned char>(s[i]) < 0x80) {
      ++n;
      ++i;
    } else {
      n += cp_cols(decode_utf8(s, i));
    }
  }
  return n;
}

bool is_upunct(uint32_t cp) {
  if (cp < 0x80) return is_ascii_punct(static_cast<int>(cp));
  size_t lo = 0, hi = sizeof(kPunct) / sizeof(kPunct[0]);
  while (lo < hi) {
    const size_t mid = (lo + hi) / 2;
    if (cp < kPunct[mid][0]) hi = mid;
    else if (cp > kPunct[mid][1]) lo = mid + 1;
    else return true;
  }
  return false;
}

bool is_uspace(uint32_t cp) {
  return cp == ' ' || cp == '\t' || cp == '\n' || cp == '\f' || cp == '\r' || cp == 0xA0 ||
         cp == 0x1680 || (cp >= 0x2000 && cp <= 0x200A) || cp == 0x202F || cp == 0x205F ||
         cp == 0x3000;
}

// Simple lowercase mapping for Latin-1, Latin Extended-A/Additional, Greek, Cyrillic and
// fullwidth Latin; other code points are returned unchanged.
uint32_t lower_cp(uint32_t cp) {
  if (cp < 0x80) return cp >= 'A' && cp <= 'Z' ? cp + 32 : cp;
  if (cp >= 0xC0 && cp <= 0xDE) return cp == 0xD7 ? cp : cp + 32;
  if (cp >= 0x100 && cp <= 0x17F) {
    if (cp == 0x130) return 'i';
    if (cp == 0x178) return 0xFF;
    if (cp == 0x138 || cp == 0x149 || cp == 0x17F) return cp;
    if ((cp >= 0x139 && cp <= 0x148) || (cp >= 0x179 && cp <= 0x17E)) return cp + (cp & 1);
    return cp | 1;
  }
  if (cp >= 0x370 && cp <= 0x3FF) {
    if (cp == 0x370 || cp == 0x372 || cp == 0x376 || (cp >= 0x3D8 && cp <= 0x3EF)) return cp | 1;
    if (cp == 0x37F) return 0x3F3;
    if (cp == 0x386) return 0x3AC;
    if (cp >= 0x388 && cp <= 0x38A) return cp + 37;
    if (cp == 0x38C) return 0x3CC;
    if (cp == 0x38E || cp == 0x38F) return cp + 63;
    if (cp >= 0x391 && cp <= 0x3AB && cp != 0x3A2) return cp + 32;
    return cp;
  }
  if (cp >= 0x400 && cp <= 0x52F) {
    if (cp <= 0x40F) return cp + 80;
    if (cp <= 0x42F) return cp + 32;
    if ((cp >= 0x460 && cp <= 0x481) || (cp >= 0x48A && cp <= 0x4BF) || cp >= 0x4D0) return cp | 1;
    if (cp == 0x4C0) return 0x4CF;
    if (cp >= 0x4C1 && cp <= 0x4CE) return cp + (cp & 1);
    return cp;
  }
  if ((cp >= 0x1E00 && cp <= 0x1E95) || (cp >= 0x1EA0 && cp <= 0x1EFF)) return cp | 1;
  if (cp == 0x1E9E) return 0xDF;
  if (cp >= 0xFF21 && cp <= 0xFF3A) return cp + 32;
  return cp;
}

// Rough Unicode simple case folding (enough for Latin, Greek, Cyrillic labels).
void fold_cp(uint32_t cp, std::string& out) {
  if (cp == 0xDF || cp == 0x1E9E) {
    out += "ss";
    return;
  }
  append_utf8(out, cp == 0x3C2 ? 0x3C3 : lower_cp(cp));
}

void escape_html(std::string& out, std::string_view s) {
  for (char c : s) {
    switch (c) {
      case '&': out += "&amp;"; break;
      case '<': out += "&lt;"; break;
      case '>': out += "&gt;"; break;
      case '"': out += "&quot;"; break;
      default: out += c; break;
    }
  }
}

std::string esc(std::string_view s) {
  std::string out;
  out.reserve(s.size());
  escape_html(out, s);
  return out;
}

// ---- entities, escapes, URLs, labels ----

const char* lookup_entity(std::string_view name) {
  size_t lo = 0, hi = sizeof(kEntities) / sizeof(kEntities[0]);
  while (lo < hi) {
    const size_t mid = (lo + hi) / 2;
    const std::string_view k = kEntities[mid].name;
    const int c = k.compare(name);
    if (c == 0) return kEntities[mid].value;
    if (c < 0) lo = mid + 1;
    else hi = mid;
  }
  return nullptr;
}

void append_cp_checked(std::string& out, uint32_t cp) {
  if (cp == 0 || cp > 0x10FFFF || (cp >= 0xD800 && cp <= 0xDFFF)) cp = 0xFFFD;
  append_utf8(out, cp);
}

// CommonMark entity at s[i] == '&': appends the decoded text and returns its length, or 0.
size_t parse_entity(std::string_view s, size_t i, std::string& out) {
  size_t j = i + 1;
  if (j < s.size() && s[j] == '#') {
    ++j;
    const bool hex = j < s.size() && (s[j] == 'x' || s[j] == 'X');
    if (hex) ++j;
    const size_t ds = j;
    uint32_t v = 0;
    while (j < s.size() && (hex ? is_xdigit(s[j]) : is_digit(s[j])) && j - ds < (hex ? 6u : 7u)) {
      const char c = s[j];
      v = v * (hex ? 16 : 10) +
          static_cast<uint32_t>(is_digit(c) ? c - '0' : lower(c) - 'a' + 10);
      ++j;
    }
    if (j == ds || j >= s.size() || s[j] != ';') return 0;
    append_cp_checked(out, v);
    return j + 1 - i;
  }
  const size_t ns = j;
  while (j < s.size() && is_alnum(s[j]) && j - ns < 32) ++j;
  if (j == ns || !is_alpha(s[ns]) || j >= s.size() || s[j] != ';') return 0;
  const char* v = lookup_entity(s.substr(ns, j - ns));
  if (!v) return 0;
  out += v;
  return j + 1 - i;
}

// Resolves backslash escapes and entities (link destinations, titles, info strings).
std::string unescape_string(std::string_view s) {
  std::string out;
  out.reserve(s.size());
  for (size_t i = 0; i < s.size();) {
    if (s[i] == '\\' && i + 1 < s.size() && is_ascii_punct(s[i + 1])) {
      out += s[i + 1];
      i += 2;
    } else if (s[i] == '&') {
      const size_t n = parse_entity(s, i, out);
      if (n) {
        i += n;
      } else {
        out += '&';
        ++i;
      }
    } else {
      out += s[i++];
    }
  }
  return out;
}

// Percent-encodes like mdurl.encode (commonmark.js normalizeURI).
std::string normalize_uri(std::string_view s) {
  static const char* hex = "0123456789ABCDEF";
  std::string out;
  out.reserve(s.size());
  for (size_t i = 0; i < s.size(); ++i) {
    const auto c = static_cast<unsigned char>(s[i]);
    if (c == '%' && i + 2 < s.size() && is_xdigit(s[i + 1]) && is_xdigit(s[i + 2])) {
      out.append(s.substr(i, 3));
      i += 2;
    } else if (is_alnum(c) || (c < 0x80 && c && std::strchr(";/?:@&=+$,-_.!~*'()#", c))) {
      out += static_cast<char>(c);
    } else {
      out += '%';
      out += hex[c >> 4];
      out += hex[c & 15];
    }
  }
  return out;
}

// Reference label (without brackets) -> lookup key: trimmed, whitespace collapsed, case folded.
std::string normalize_label(std::string_view s) {
  s = trim_ws(s);
  std::string out;
  bool space = false;
  for (size_t i = 0; i < s.size();) {
    if (is_ws(s[i])) {
      space = true;
      ++i;
      continue;
    }
    if (space) out += ' ';
    space = false;
    fold_cp(decode_utf8(s, i), out);
  }
  return out;
}

bool dangerous_url(std::string_view url) {
  size_t i = 0;
  while (i < url.size() && static_cast<unsigned char>(url[i]) <= 0x20) ++i;
  std::string u;
  for (; i < url.size() && u.size() < 32; ++i) {
    const auto c = static_cast<unsigned char>(url[i]);
    if (c <= 0x20 || c == 0x7F) continue;
    u += lower(static_cast<char>(c));
  }
  if (istarts(u, "javascript:") || istarts(u, "vbscript:") || istarts(u, "file:")) return true;
  if (istarts(u, "data:")) {
    for (const char* ok : {"data:image/png", "data:image/gif", "data:image/jpeg", "data:image/webp"}) {
      if (istarts(u, ok)) return false;
    }
    return true;
  }
  return false;
}

// Caches the result of a forward search so repeated scans from increasing offsets stay linear.
struct FindCache {
  bool valid = false;
  size_t from = 0, at = 0;
  size_t find(std::string_view s, std::string_view needle, size_t f) {
    if (valid && from <= f && (at == npos || at >= f)) return at;
    valid = true;
    from = f;
    at = s.find(needle, f);
    return at;
  }
};

// ---- HTML syntax scanners (CommonMark grammar) ----

struct HtmlCaches {
  FindCache comment, pi, cdata, decl, dquote, squote;
};

size_t skip_html_ws(std::string_view s, size_t i) {
  while (i < s.size() && is_ws(s[i])) ++i;
  return i;
}

// Open tag at s[p] == '<'; returns end offset or 0.
size_t scan_open_tag(std::string_view s, size_t p, HtmlCaches* c) {
  size_t i = p + 1;
  if (i >= s.size() || !is_alpha(s[i])) return 0;
  while (i < s.size() && (is_alnum(s[i]) || s[i] == '-')) ++i;
  for (;;) {
    const size_t ws = skip_html_ws(s, i);
    if (ws == i || ws >= s.size()) break;
    const char a = s[ws];
    if (!(is_alpha(a) || a == '_' || a == ':')) break;
    size_t j = ws + 1;
    while (j < s.size() && (is_alnum(s[j]) || s[j] == '_' || s[j] == '.' || s[j] == ':' || s[j] == '-')) ++j;
    i = j;
    size_t k = skip_html_ws(s, j);
    if (k < s.size() && s[k] == '=') {
      k = skip_html_ws(s, k + 1);
      if (k >= s.size()) return 0;
      if (s[k] == '"' || s[k] == '\'') {
        size_t e;
        if (c) e = (s[k] == '"' ? c->dquote : c->squote).find(s, std::string_view(&s[k], 1), k + 1);
        else e = s.find(s[k], k + 1);
        if (e == npos) return 0;
        i = e + 1;
      } else {
        size_t e = k;
        while (e < s.size() && !std::strchr("\"'=<>`", s[e]) &&
               static_cast<unsigned char>(s[e]) > 0x20)
          ++e;
        if (e == k) return 0;
        i = e;
      }
    }
  }
  i = skip_html_ws(s, i);
  if (i < s.size() && s[i] == '/') ++i;
  if (i < s.size() && s[i] == '>') return i + 1;
  return 0;
}

size_t scan_close_tag(std::string_view s, size_t p) {
  size_t i = p + 2;
  if (p + 1 >= s.size() || s[p + 1] != '/' || i >= s.size() || !is_alpha(s[i])) return 0;
  while (i < s.size() && (is_alnum(s[i]) || s[i] == '-')) ++i;
  i = skip_html_ws(s, i);
  if (i < s.size() && s[i] == '>') return i + 1;
  return 0;
}

// Any inline raw HTML at s[p] == '<'; returns end offset or 0.
size_t scan_html_inline(std::string_view s, size_t p, HtmlCaches& c) {
  if (p + 1 >= s.size()) return 0;
  const char n = s[p + 1];
  if (is_alpha(n)) return scan_open_tag(s, p, &c);
  if (n == '/') return scan_close_tag(s, p);
  if (n == '?') {
    const size_t e = c.pi.find(s, "?>", p + 2);
    return e == npos ? 0 : e + 2;
  }
  if (n != '!') return 0;
  const std::string_view r = s.substr(p);
  if (r.substr(0, 4) == "<!--") {
    if (r.substr(0, 5) == "<!-->") return p + 5;
    if (r.substr(0, 6) == "<!--->") return p + 6;
    const size_t e = c.comment.find(s, "-->", p + 4);
    return e == npos ? 0 : e + 3;
  }
  if (r.substr(0, 9) == "<![CDATA[") {
    const size_t e = c.cdata.find(s, "]]>", p + 9);
    return e == npos ? 0 : e + 3;
  }
  if (p + 2 < s.size() && is_alpha(s[p + 2])) {
    const size_t e = c.decl.find(s, ">", p + 2);
    return e == npos ? 0 : e + 1;
  }
  return 0;
}

const char* const kBlockTags[] = {
    "address", "article", "aside", "base", "basefont", "blockquote", "body", "caption", "center",
    "col", "colgroup", "dd", "details", "dialog", "dir", "div", "dl", "dt", "fieldset",
    "figcaption", "figure", "footer", "form", "frame", "frameset", "h1", "h2", "h3", "h4", "h5",
    "h6", "head", "header", "hr", "html", "iframe", "legend", "li", "link", "main", "menu",
    "menuitem", "nav", "noframes", "ol", "optgroup", "option", "p", "param", "search", "section",
    "summary", "table", "tbody", "td", "tfoot", "th", "thead", "title", "tr", "track", "ul"};

// HTML block start kind (1-7) for a line starting with '<', or 0.
int html_block_start(std::string_view s, bool can_be_7) {
  if (s.size() < 2 || s[0] != '<') return 0;
  auto name_end = [&](size_t i) {
    while (i < s.size() && is_alnum(s[i])) ++i;
    return i;
  };
  if (is_alpha(s[1])) {
    const size_t e = name_end(1);
    const std::string n = to_lower(s.substr(1, e - 1));
    if ((n == "script" || n == "pre" || n == "textarea" || n == "style") &&
        (e == s.size() || is_sp_tab(s[e]) || s[e] == '>'))
      return 1;
  }
  if (s.substr(0, 4) == "<!--") return 2;
  if (s[1] == '?') return 3;
  if (s.substr(0, 9) == "<![CDATA[") return 5;
  if (s[1] == '!' && s.size() > 2 && is_alpha(s[2])) return 4;
  const size_t ns = s[1] == '/' ? 2 : 1;
  if (ns < s.size() && is_alpha(s[ns])) {
    const size_t e = name_end(ns);
    const std::string n = to_lower(s.substr(ns, e - ns));
    for (const char* t : kBlockTags) {
      if (n == t) {
        if (e == s.size() || is_sp_tab(s[e]) || s[e] == '>' || s.substr(e, 2) == "/>") return 6;
        break;
      }
    }
  }
  if (can_be_7) {
    size_t e = s[1] == '/' ? scan_close_tag(s, 0) : scan_open_tag(s, 0, nullptr);
    if (e) {
      const size_t ns2 = s[1] == '/' ? 2 : 1;
      const std::string n = to_lower(s.substr(ns2, name_end(ns2) - ns2));
      if (n != "script" && n != "style" && n != "pre" && n != "textarea" && is_blank(s.substr(e)))
        return 7;
    }
  }
  return 0;
}

bool html_block_ends(int type, std::string_view s) {
  switch (type) {
    case 1:
      return ifind(s, "</script>") != npos || ifind(s, "</pre>") != npos ||
             ifind(s, "</textarea>") != npos || ifind(s, "</style>") != npos;
    case 2: return s.find("-->") != npos;
    case 3: return s.find("?>") != npos;
    case 4: return s.find('>') != npos;
    case 5: return s.find("]]>") != npos;
    default: return false;
  }
}

// ---- link syntax scanners (shared by inlines and reference definitions) ----

// Optional spaces/tabs with at most one line ending.
size_t skip_spnl(std::string_view s, size_t i) {
  while (i < s.size() && is_sp_tab(s[i])) ++i;
  if (i < s.size() && s[i] == '\n') {
    ++i;
    while (i < s.size() && is_sp_tab(s[i])) ++i;
  }
  return i;
}

// [label] at s[i] == '['; returns its length (including brackets) or 0.
size_t scan_link_label(std::string_view s, size_t i) {
  if (i >= s.size() || s[i] != '[') return 0;
  size_t j = i + 1;
  int units = 0;
  while (j < s.size()) {
    const char c = s[j];
    if (c == ']') return units <= 999 ? j - i + 1 : 0;
    if (c == '[') return 0;
    if (c == '\\') {
      if (j + 1 >= s.size()) return 0;
      j += 2;
    } else {
      ++j;
    }
    if (++units > 999) return 0;
  }
  return 0;
}

// Link destination at s[i]; sets dest (unescaped, normalized) and the end offset.
bool scan_link_dest(std::string_view s, size_t i, size_t& end, std::string& dest) {
  if (i < s.size() && s[i] == '<') {
    size_t j = i + 1;
    while (j < s.size()) {
      const char c = s[j];
      if (c == '>') {
        dest = normalize_uri(unescape_string(s.substr(i + 1, j - i - 1)));
        end = j + 1;
        return true;
      }
      if (c == '<' || c == '\n') return false;
      if (c == '\\' && j + 1 < s.size() && s[j + 1] != '\n') j += 2;
      else ++j;
    }
    return false;
  }
  size_t j = i;
  int parens = 0;
  while (j < s.size()) {
    const auto c = static_cast<unsigned char>(s[j]);
    if (c == '\\' && j + 1 < s.size() && is_ascii_punct(s[j + 1])) {
      j += 2;
    } else if (c == '(') {
      if (++parens > 32) return false;
      ++j;
    } else if (c == ')') {
      if (parens < 1) break;
      --parens;
      ++j;
    } else if (c <= 0x20 || c == 0x7F) {
      break;
    } else {
      ++j;
    }
  }
  if (j == i && (j >= s.size() || s[j] != ')')) return false;
  if (parens != 0) return false;
  dest = normalize_uri(unescape_string(s.substr(i, j - i)));
  end = j;
  return true;
}

bool scan_link_title(std::string_view s, size_t i, size_t& end, std::string& title) {
  if (i >= s.size()) return false;
  const char open = s[i];
  const char close = open == '(' ? ')' : open;
  if (open != '"' && open != '\'' && open != '(') return false;
  size_t j = i + 1;
  while (j < s.size()) {
    const char c = s[j];
    if (c == '\\' && j + 1 < s.size()) {
      j += 2;
      continue;
    }
    if (c == close) {
      title = unescape_string(s.substr(i + 1, j - i - 1));
      end = j + 1;
      return true;
    }
    if (open == '(' && c == '(') return false;
    ++j;
  }
  return false;
}

// End of trailing spaces then line end (or end of input), or npos.
size_t space_to_eol(std::string_view s, size_t i) {
  while (i < s.size() && is_sp_tab(s[i])) ++i;
  if (i == s.size()) return i;
  if (s[i] == '\n') return i + 1;
  return npos;
}

